/**
 * Retorna a URL interna de redirecionamento (ex: '/aluguel-de-van-com-motorista-1')
 * com base no caminho da página atual.
 */
export function getButtonHrefForPage(path = '') {
  const p = path.toLowerCase();

  if (p.includes('/aluguel-de-van-sem-motorista')) {
    return '/aluguel-de-van-sem-motorista-1/';
  }
  if (p.includes('/aluguel-de-van-com-motorista')) {
    return '/aluguel-de-van-com-motorista-1/';
  }
  if (p.includes('/aluguel-de-van-para-viagem')) {
    return '/aluguel-de-van-para-viagem-1/';
  }
  if (p.includes('/aluguel-de-mini-van-7-lugares') || p.includes('/aluguel-de-minivan-7-lugares')) {
    return '/aluguel-de-mini-van-7-lugares-1/';
  }
  if (p.includes('/aluguel-de-mini-van') || p.includes('/aluguel-de-minivan')) {
    return '/aluguel-de-mini-van-1/';
  }
  if (p.includes('/aluguel-de-van-12-lugares')) {
    return '/aluguel-de-van-12-lugares-1/';
  }
  if (p.includes('/aluguel-de-van-15-lugares') || p.includes('/aluguel-de-van-de-15-lugares')) {
    return '/aluguel-de-van-de-15-lugares-1/';
  }
  if (p.includes('/aluguel-de-van-18-lugares')) {
    return '/aluguel-de-van-18-lugares-1/';
  }
  if (p.includes('/aluguel-de-van-de-carga')) {
    return '/aluguel-de-van-de-carga-1/';
  }
  if (p.includes('/aluguel-de-van-furgao')) {
    return '/aluguel-de-van-furgao-1/';
  }
  if (p.includes('/aluguel-de-van-para-passeio')) {
    return '/aluguel-de-van-para-passeio-1/';
  }
  if (p.includes('/aluguel-de-van-para-praias') || p.includes('/aluguel-de-van-para-praia')) {
    return '/aluguel-de-van-para-praias-1/';
  }
  if (p.includes('/aluguel-de-van-para-casamento')) {
    return '/aluguel-de-van-para-casamento-1/';
  }
  if (p.includes('guarulhos')) {
    return 'https://alugueldevansp.com/aluguel-de-van-1';
  }
  if (p.includes('/aluguel-de-van')) {
    return 'https://alugueldevansp.com/aluguel-de-van-1';
  }

  // Demais páginas no site
  return '/solicite-um-orcamento/';
}

/**
 * Retorna o link final do WhatsApp para uma URL interna de redirecionamento ou página.
 */
export function getWhatsAppUrl(hrefOrPath = '') {
  const clean = hrefOrPath.trim().replace(/\/$/, '');
  if (WHATSAPP_REDIRECTS[clean]) return WHATSAPP_REDIRECTS[clean];
  if (WHATSAPP_REDIRECTS[clean + '/']) return WHATSAPP_REDIRECTS[clean + '/'];

  const internalHref = getButtonHrefForPage(clean);
  return WHATSAPP_REDIRECTS[internalHref] || WHATSAPP_REDIRECTS['/solicite-um-orcamento'];
}
